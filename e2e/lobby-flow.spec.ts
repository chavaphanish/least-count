import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
async function guest(page: Page, displayName: string) {
  const origin = new URL(test.info().project.use.baseURL as string).origin
  const response = await page.request.post('/api/guest', { headers: { Origin: origin }, data: { displayName } })
  expect(response.ok()).toBe(true)
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Host a Game', exact: true })).toBeVisible()
}
test('real rooms synchronize lobby settings, invitation joins, disconnects, host handover and start', async ({ browser }) => {
  test.setTimeout(90000)
  const a = await browser.newContext(), b = await browser.newContext()
  try {
    const host = await a.newPage(), friend = await b.newPage()
    await guest(host, 'Lobby Host'); await guest(friend, 'Lobby Friend')
    await host.getByRole('button', { name: 'Host a Game', exact: true }).click()
    await expect(host.getByRole('heading', { name: 'Waiting lobby' })).toBeVisible()
    const code = (await host.locator('.room-code-panel strong').textContent())!
    await host.getByLabel('Number of players').selectOption('2')
    await expect(host.getByLabel('Number of players')).toBeEnabled()
    await host.getByLabel('Elimination threshold').selectOption('150')
    await expect(host.getByLabel('Elimination threshold')).toBeEnabled()
    await expect(host.getByRole('button', { name: 'Start Game', exact: true })).toBeDisabled()
    await friend.goto(`/join/${code}`)
    await expect(friend.getByRole('heading', { name: 'Waiting lobby' })).toBeVisible()
    await expect(friend).toHaveURL(new RegExp(`#/room/${code}$`))
    await expect(friend.locator('.lobby-settings select')).toHaveCount(0)
    await expect(friend.locator('.lobby-settings')).toContainText('150')
    await expect(host.getByRole('heading', { name: '2/2 Players', exact: true })).toBeVisible()
    await expect(host.getByRole('button', { name: 'Start Game', exact: true })).toBeEnabled()
    const ids = await host.locator('[data-player-id]').evaluateAll(els => els.map(el => el.getAttribute('data-player-id')))
    await host.getByLabel('Number of players').selectOption('3')
    await expect(friend.getByRole('heading', { name: '2/3 Players', exact: true })).toBeVisible()
    expect(await host.locator('[data-player-id]').evaluateAll(els => els.map(el => el.getAttribute('data-player-id')))).toEqual(ids)
    await expect(host.getByRole('button', { name: 'Start Game', exact: true })).toBeDisabled()
    await host.getByLabel('Number of players').selectOption('2')
    await expect(host.getByRole('button', { name: 'Start Game', exact: true })).toBeEnabled()
    await b.setOffline(true)
    await expect(host.getByRole('heading', { name: '1/2 Players', exact: true })).toBeVisible()
    await expect(host.getByRole('button', { name: 'Start Game', exact: true })).toBeDisabled()
    await expect(host.locator('.disconnected-player')).toHaveCount(1)
    await b.setOffline(false)
    await expect(host.getByRole('button', { name: 'Start Game', exact: true })).toBeEnabled()
    await host.getByRole('button', { name: 'Leave Room', exact: true }).click()
    await expect(friend.getByLabel('Number of players')).toBeEnabled()
    await expect(friend.getByRole('button', { name: 'Start Game', exact: true })).toBeDisabled()
    await host.goto(`/join/${code}`)
    await expect(friend.getByRole('button', { name: 'Start Game', exact: true })).toBeEnabled()
    await expect(host.locator('.lobby-settings select')).toHaveCount(0)
    await friend.getByRole('button', { name: 'Start Game', exact: true }).click()
    await expect(friend.locator('.active-game')).toBeVisible()
    await expect(host.locator('.active-game')).toBeVisible()
    const snapshot = await (await friend.request.get(`/api/rooms/${code}`)).json()
    expect(snapshot.settings).toEqual({ maxPlayers: 2, eliminationThreshold: 150, timedGame: true, turnDurationSeconds: 45 })
    expect(snapshot.game.players).toHaveLength(2)
    await expect(friend.locator('.lobby-settings')).toHaveCount(0)
  } finally { await a.close(); await b.close() }
})

test('a confirmed quit blocks rejoining until the winner returns the same room to its lobby', async ({ browser, baseURL }) => {
  test.setTimeout(60000)
  const a = await browser.newContext(), b = await browser.newContext()
  try {
    const host = await a.newPage(), friend = await b.newPage()
    await guest(host, 'First Host')
    await guest(friend, 'Next Host')
    await host.getByRole('button', {name:'Host a Game'}).click()
    const code = await host.locator('.room-code-panel strong').innerText()
    await host.getByLabel('Number of players').selectOption('2')
    await friend.goto(`/join/${code}`)
    await host.getByRole('button', {name:'Start Game', exact:true}).click()
    await host.getByRole('button', {name:'Scorecard', exact:true}).click()
    await host.getByRole('dialog', {name:'Scorecard', exact:true}).getByRole('button',{name:'Quit Game', exact:true}).click()
    await host.getByRole('dialog', {name:'Quit Game?', exact:true}).getByRole('button',{name:'Quit Game', exact:true}).click()
    await expect(host.getByRole('button', {name:'Host a Game'})).toBeVisible()
    await expect(friend.getByRole('heading', {name:'Next Host wins the game!'})).toBeVisible()
    expect((await host.request.post(`/api/rooms/${code}/join`, {headers:{Origin:baseURL!}})).status()).toBe(403)
    await friend.getByRole('button',{name:'Return to Lobby'}).click()
    await expect(friend.getByRole('heading',{name:'Waiting lobby'})).toBeVisible()
    await expect(friend.getByLabel('Number of players')).toHaveValue('2')
    await host.goto(`/join/${code}`)
    await friend.getByRole('button',{name:'Start Game',exact:true}).click()
    await expect(host.getByRole('button',{name:'Scorecard',exact:true})).toBeVisible()
  } finally { await a.close(); await b.close() }
})
